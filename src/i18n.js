const getSavedLanguage = () => {
  if (typeof window !== 'undefined') {
    const saved = localStorage.getItem('rosha_admin_lang');
    if (saved && ['en', 'sv', 'fa'].includes(saved)) {
      return saved;
    }
  }
  return 'en';
};

const initialLang = getSavedLanguage();

i18n.use(initReactI18next).init({
  resources,
  lng: initialLang,
  fallbackLng: 'en',
  interpolation: {
    escapeValue: false,
  },
});

export const updateDocumentDirection = (lang) => {
  if (typeof window !== 'undefined') {
    const isRtl = lang === 'fa';
    document.documentElement.dir = isRtl ? 'rtl' : 'ltr';
    document.documentElement.lang = lang;
    if (isRtl) {
      document.documentElement.classList.add('rtl-layout');
    } else {
      document.documentElement.classList.remove('rtl-layout');
    }
  }
};

export const changeAdminLanguage = async (newLang) => {
  if (!['en', 'sv', 'fa'].includes(newLang)) return;
  await i18n.changeLanguage(newLang);
  if (typeof window !== 'undefined') {
    localStorage.setItem('rosha_admin_lang', newLang);
  }
  updateDocumentDirection(newLang);
};

// Initial document direction setup
updateDocumentDirection(initialLang);

export default i18n;
